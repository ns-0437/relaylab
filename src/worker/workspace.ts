// Phase 2A: a task-specific MANAGED WORKSPACE ROOT, and the path-
// boundary checks that keep every worktree this worker creates strictly
// inside it. Never the user's normal working directory, never reused
// across unrelated tasks, never cleaned/reset outside its own subtree.
import { mkdir, rm, lstat, stat, realpath } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

/**
 * The root directory ALL of this worker's managed task worktrees live
 * under. **Deliberately STABLE across process restarts by default**
 * (`RELAYLAB_WORKER_WORKSPACE_ROOT`, falling back to a FIXED, well-known
 * path under the OS temp directory -- not randomized) -- this is what
 * makes restart reconciliation (Part G) actually possible: a worktree
 * path is derived deterministically from `(managedRoot, taskId,
 * attemptId)` alone (see `resolveWorktreePath` below), so a RESTARTED
 * worker process can only find a PRIOR attempt's worktree on disk if it
 * resolves to the SAME path -- which requires the SAME managed root. An
 * earlier version of this function used `mkdtemp` (a fresh random
 * directory every call), which silently broke reconciliation: every
 * restart got its own, unrelated workspace root and could never find
 * the previous attempt's worktree at all. Caught by
 * `tests/integration/git-worker-crash.ts`'s real kill-and-restart test.
 * Callers that genuinely want isolation (e.g. two unrelated test runs
 * that must never see each other's worktrees) pass an explicit
 * `root` override.
 */
export async function createManagedWorkspaceRoot(root?: string): Promise<string> {
  const target = root ?? process.env.RELAYLAB_WORKER_WORKSPACE_ROOT ?? path.join(tmpdir(), "relaylab-worker-workspace");
  await mkdir(target, { recursive: true });
  return target;
}

/**
 * Resolves a task's deterministic worktree path WITHIN the managed root,
 * and verifies the resolved, absolute path actually stays inside it --
 * `taskId`/`attemptId` are caller-controlled strings (task IDs are
 * generated by this project's own code, but are still validated here
 * defensively against path traversal, e.g. a task ID containing `..` or
 * an absolute-path-like string could otherwise escape the managed root).
 */
export function resolveWorktreePath(managedRoot: string, taskId: string, attemptId: string): string {
  assertSafePathSegment(taskId, "taskId");
  assertSafePathSegment(attemptId, "attemptId");
  const resolvedRoot = path.resolve(managedRoot);
  const candidate = path.resolve(resolvedRoot, taskId, attemptId);
  assertWithinRoot(resolvedRoot, candidate);
  return candidate;
}

/** Resolves (and validates) the isolated HOME/git-config directory for one worker process, separate from any worktree. */
export function resolveIsolatedHomeDir(managedRoot: string): string {
  const resolvedRoot = path.resolve(managedRoot);
  const candidate = path.resolve(resolvedRoot, ".home");
  assertWithinRoot(resolvedRoot, candidate);
  return candidate;
}

function assertSafePathSegment(segment: string, label: string): void {
  if (segment.length === 0 || segment.length > 191) {
    throw new Error(`${label} must be a non-empty string of at most 191 characters, got ${JSON.stringify(segment)}`);
  }
  // Deliberately conservative allowlist (alphanumeric, dash, underscore)
  // -- this project's own task IDs already match this shape (see
  // uniqueId() in tests/integration/helpers.ts and *-main.ts's OWNER_ID
  // pattern); anything else is REJECTED explicitly rather than
  // sanitized/escaped, per Part D: "reject unsupported ... configurations
  // explicitly rather than corrupting state."
  if (!/^[A-Za-z0-9_-]+$/.test(segment)) {
    throw new Error(`${label} contains characters outside the safe allowlist [A-Za-z0-9_-]: ${JSON.stringify(segment)}`);
  }
}

/** Throws unless `candidate` is `root` itself or strictly nested inside it, after both are resolved to absolute, normalized paths (handles spaces and `..`/symlink-style traversal attempts alike). */
export function assertWithinRoot(root: string, candidate: string): void {
  const resolvedRoot = path.resolve(root);
  const resolvedCandidate = path.resolve(candidate);
  const rootWithSep = resolvedRoot.endsWith(path.sep) ? resolvedRoot : resolvedRoot + path.sep;
  if (resolvedCandidate !== resolvedRoot && !resolvedCandidate.startsWith(rootWithSep)) {
    throw new Error(`path "${resolvedCandidate}" escapes the managed workspace root "${resolvedRoot}"`);
  }
}

export async function ensureDir(dir: string): Promise<void> {
  await mkdir(dir, { recursive: true });
}

/**
 * Phase 2A.1, section 6: `assertWithinRoot` above is PURELY LEXICAL
 * (string comparison on `path.resolve()`'d paths) -- it cannot detect a
 * directory INSIDE the managed root that is actually a symlink/NTFS
 * junction/reparse point pointing somewhere else entirely, which would
 * let a worktree operation escape the managed root despite passing the
 * lexical check. This walks every path SEGMENT that actually exists on
 * disk, from the root down to the candidate, and rejects if any of them
 * is a symlink (`lstat().isSymbolicLink()` -- on Windows this also
 * covers NTFS junctions created via `mklink /J`/`fsutil reparsepoint`,
 * per Node's documented reparse-point handling; this was reasoned from
 * Node's own fs documentation and NOT exhaustively verified against
 * every exotic Windows reparse-point type on this host -- see
 * docs/ARCHITECTURE.md "Phase 2A worker" for this stated, untested-
 * platform-behavior disclosure). A final `realpath` comparison on the
 * deepest EXISTING ancestor is a belt-and-suspenders check against
 * anything the segment walk might have missed.
 *
 * Only checks segments that EXIST -- a worktree path that does not
 * exist yet (the normal "about to create it" case) has nothing to
 * check below its deepest existing ancestor, which is correct: there is
 * no symlink to reject if nothing is there yet.
 */
export async function assertNoSymlinkEscapes(root: string, candidate: string): Promise<void> {
  const resolvedRoot = path.resolve(root);
  const resolvedCandidate = path.resolve(candidate);
  assertWithinRoot(resolvedRoot, resolvedCandidate); // cheap lexical check first

  await rejectIfSymlink(resolvedRoot);
  const relative = path.relative(resolvedRoot, resolvedCandidate);
  const segments = relative.length === 0 ? [] : relative.split(path.sep);
  let current = resolvedRoot;
  for (const segment of segments) {
    current = path.join(current, segment);
    const exists = await stat(current).then(
      () => true,
      () => false,
    );
    if (!exists) break; // nothing further down exists yet -- nothing more to check
    await rejectIfSymlink(current);
  }

  // Belt-and-suspenders: compare the REAL (symlink/junction-resolved)
  // path of the deepest EXISTING ancestor against the REAL path of the
  // root itself -- NOT against its own lexical self. On Windows, a
  // path containing a space in the username is commonly reported in
  // its 8.3 short-name form by `os.tmpdir()`/env vars (e.g.
  // `NAVINK~1`) while `fs.realpath` normalizes to the long form (e.g.
  // `Navin Kumar`); comparing a realpath'd value against its own
  // UN-realpath'd lexical form would treat this harmless OS-level
  // aliasing as an escape. Comparing REAL-to-REAL (root's real path vs.
  // candidate's real path) avoids that false positive while still
  // catching a genuine symlink/junction that points somewhere outside
  // the root's real location.
  let deepestExisting = resolvedCandidate;
  while (!(await stat(deepestExisting).then(() => true, () => false))) {
    const parent = path.dirname(deepestExisting);
    if (parent === deepestExisting) break; // reached filesystem root without finding anything -- nothing to check
    deepestExisting = parent;
  }
  const realRoot = await realpath(resolvedRoot);
  const realDeepestExisting = await realpath(deepestExisting);
  const realRootWithSep = realRoot.endsWith(path.sep) ? realRoot : realRoot + path.sep;
  if (realDeepestExisting !== realRoot && !realDeepestExisting.startsWith(realRootWithSep)) {
    throw new Error(
      `path "${deepestExisting}" resolves through a symlink/junction to "${realDeepestExisting}", which is OUTSIDE the managed root's own real location ("${realRoot}") -- refusing to operate on it`,
    );
  }
}

async function rejectIfSymlink(p: string): Promise<void> {
  try {
    const st = await lstat(p);
    if (st.isSymbolicLink()) {
      throw new Error(`"${p}" is a symlink/junction/reparse point -- rejected explicitly (managed-workspace paths must be real directories, never a link that could escape the managed root)`);
    }
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return; // doesn't exist yet -- nothing to check
    throw err;
  }
}

/**
 * STRICTER than `assertWithinRoot`/`assertNoSymlinkEscapes` alone --
 * section 6: "treat deletion/cleanup paths more strictly than paths
 * merely being inspected" and "do not allow a task cleanup operation to
 * target the managed root itself." Requires the target to be EXACTLY 2
 * segments below the root (a specific task's specific attempt worktree
 * -- `taskId/attemptId`), never the root itself, never a shallower or
 * deeper path. Any caller that wants to delete something must pass
 * through this, not `assertWithinRoot` alone.
 */
export async function assertSafeForDeletion(managedRoot: string, target: string): Promise<void> {
  const resolvedRoot = path.resolve(managedRoot);
  const resolvedTarget = path.resolve(target);
  if (resolvedTarget === resolvedRoot) {
    throw new Error(`refusing to delete the managed workspace root itself ("${resolvedRoot}") -- a cleanup operation must target one SPECIFIC task's worktree, never the root`);
  }
  await assertNoSymlinkEscapes(resolvedRoot, resolvedTarget);
  const relative = path.relative(resolvedRoot, resolvedTarget);
  const depth = relative.split(path.sep).filter(Boolean).length;
  if (depth !== 2) {
    throw new Error(`refusing to delete "${resolvedTarget}" -- expected EXACTLY a (taskId, attemptId) worktree path (2 segments below the managed root), got ${depth} segment(s)`);
  }
}

/** Removes the ENTIRE managed workspace root (all tasks' worktrees under it) -- only ever called on worker shutdown, never mid-task, and never confused with per-task cleanup (`assertSafeForDeletion` is deliberately NOT used here -- this function's entire point IS to remove the root). */
export async function removeManagedWorkspaceRoot(managedRoot: string): Promise<void> {
  await rm(managedRoot, { recursive: true, force: true }).catch(() => {});
}
